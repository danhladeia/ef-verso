import {chromium} from '@playwright/test';
import fs from 'node:fs';
const browser=await chromium.launch({channel:'msedge',headless:true});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('response',r=>{if(r.status()>=400)errors.push(r.status()+' '+r.url());});
await page.goto('http://localhost:5173/');
await page.waitForFunction(()=>window.cityReady,null,{timeout:60000});
await page.waitForTimeout(1500);
await page.screenshot({path:'art-source/cidade-atual.png'});
const desktop=await page.evaluate(()=>({stats:window.cityStats(),design:window.cityDesign}));
await page.locator('#admin-flight').click();
await page.waitForTimeout(500);
await page.screenshot({path:'art-source/cidade-aerea.png'});
await page.locator('[data-action="exit"]').click();
await page.locator('#camera').click();await page.waitForTimeout(400);
await page.screenshot({path:'art-source/cidade-terceira-pessoa.png'});
const mobile=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:1});const phone=await mobile.newPage();phone.on('pageerror',e=>errors.push(e.message));
await phone.goto('http://localhost:5173/');await phone.waitForFunction(()=>window.cityReady,null,{timeout:60000});await phone.waitForTimeout(500);
await phone.screenshot({path:'art-source/cidade-mobile.png'});
console.log(JSON.stringify({errors,desktop,mobile:await phone.evaluate(()=>({stats:window.cityStats(),overflow:document.documentElement.scrollWidth>innerWidth})),status:await page.locator('#status').textContent()}));
await browser.close();if(errors.length)process.exitCode=1;
